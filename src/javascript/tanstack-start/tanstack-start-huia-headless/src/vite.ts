import fs from 'node:fs'
import path from 'node:path'
import type { Plugin } from 'vite'
import type { HuiaVitePluginOptions } from './types.js'

export function huiaHeadless(options: HuiaVitePluginOptions = {}): Plugin {
  return {
    name: 'huia-tanstack-start-headless',
    configResolved(config) {
      const sessionPassword = process.env.HUIA_SESSION_PASSWORD
      if (sessionPassword && sessionPassword.length < 32) {
        throw new Error('[@huia/tanstack-start-headless] HUIA_SESSION_PASSWORD must be at least 32 characters long.')
      }

      if (options.disableScaffolding) {
        return
      }

      const root = config.root || process.cwd()
      const routeRelPath = options.routeFile ?? path.join('src', 'routes', 'api', 'auth', '$.ts')
      const routeAbsPath = path.isAbsolute(routeRelPath) ? routeRelPath : path.join(root, routeRelPath)

      if (!fs.existsSync(routeAbsPath)) {
        const authImport = options.authConfigImportPath ?? '@/auth.config'
        const dir = path.dirname(routeAbsPath)
        if (!fs.existsSync(dir)) {
          fs.mkdirSync(dir, { recursive: true })
        }

        const template = `// Generated by @huia/tanstack-start-headless
import { createFileRoute } from '@tanstack/react-router'
import { createHuiaHeadlessHandler } from '@huia/tanstack-start-headless/server'
import { huiaConfig } from '${authImport}'

const handler = createHuiaHeadlessHandler(huiaConfig)

export const Route = createFileRoute('/api/auth/$')({
  server: {
    handlers: {
      GET: async ({ request }) => handler(request),
      POST: async ({ request }) => handler(request),
      PUT: async ({ request }) => handler(request),
      PATCH: async ({ request }) => handler(request),
      DELETE: async ({ request }) => handler(request),
    },
  },
})
`
        fs.writeFileSync(routeAbsPath, template, 'utf8')
      }
    },
  }
}
